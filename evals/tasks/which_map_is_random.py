"""Task 01 — which of two point patterns is the truly random one?

Companion to alestainer.com/blog/which-map-is-random. One panel is a
homogeneous Poisson process, the other is a hard-core process with a minimum
separation. Humans reliably pick the hard-core one.
"""
import os
import random

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from .base import Task, Trial

N = 120
MIN_SEP = 0.028


def _poisson(rng, n):
    return [(rng.random(), rng.random()) for _ in range(n)]


def _hardcore(rng, n, min_sep):
    pts, r2, attempts = [], min_sep ** 2, 0
    while len(pts) < n and attempts < n * 8000:
        attempts += 1
        x, y = rng.random(), rng.random()
        if all((px - x) ** 2 + (py - y) ** 2 >= r2 for px, py in pts):
            pts.append((x, y))
    return pts


def _render(path, left_pts, right_pts):
    fig, axes = plt.subplots(1, 2, figsize=(10, 5.2), dpi=110)
    for ax, pts, label in zip(axes, (left_pts, right_pts), ("LEFT", "RIGHT")):
        ax.scatter([p[0] for p in pts], [p[1] for p in pts], s=14, c="#1e293b")
        ax.set_xlim(0, 1); ax.set_ylim(0, 1)
        ax.set_xticks([]); ax.set_yticks([])
        ax.set_title(label, fontsize=13, color="#334155")
        for spine in ax.spines.values():
            spine.set_color("#cbd5e1")
    fig.tight_layout()
    fig.savefig(path, facecolor="white")
    plt.close(fig)


class WhichMapIsRandom(Task):
    slug = "which-map-is-random"
    question = (
        "The image shows two squares of dots, labelled LEFT and RIGHT. "
        "Exactly one of them was generated by a truly random process; the other was generated "
        "by a different process. Which square was generated by the truly random process?"
    )

    def build(self, out_dir, n=20, seed=7):
        """Half the trials are fresh; each is paired with its left-right mirror.

        The mirror pair is the position-bias control: a model that reads the
        pattern must flip its answer, a model answering by position will not.
        """
        os.makedirs(out_dir, exist_ok=True)
        rng = random.Random(seed)
        trials = []
        for i in range(n // 2):
            base_seed = rng.randrange(10 ** 9)
            g1, g2 = random.Random(base_seed), random.Random(base_seed ^ 0x5DEECE66D)
            poisson_pts = _poisson(g1, N)
            hard_pts = _hardcore(g2, N, MIN_SEP)
            if len(hard_pts) < N:
                continue
            poisson_left = rng.random() < 0.5

            tid = f"t{i:02d}"
            p = os.path.join(out_dir, f"{tid}.png")
            _render(p, poisson_pts if poisson_left else hard_pts,
                       hard_pts if poisson_left else poisson_pts)
            trials.append(Trial(tid, p, "LEFT" if poisson_left else "RIGHT",
                                ["LEFT", "RIGHT"], meta={"seed": base_seed}))

            mid = f"{tid}m"
            pm = os.path.join(out_dir, f"{mid}.png")
            _render(pm, hard_pts if poisson_left else poisson_pts,
                        poisson_pts if poisson_left else hard_pts)
            trials.append(Trial(mid, pm, "RIGHT" if poisson_left else "LEFT",
                                ["LEFT", "RIGHT"], mirror_of=tid,
                                meta={"seed": base_seed}))
        return trials


TASK = WhichMapIsRandom()
